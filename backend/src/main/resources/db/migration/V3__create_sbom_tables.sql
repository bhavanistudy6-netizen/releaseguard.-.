CREATE TABLE sbom_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    release_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    bom_format VARCHAR(30) NOT NULL,
    spec_version VARCHAR(20) NOT NULL,
    document_sha256 VARCHAR(64) NOT NULL,

    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sbom_documents_release
        FOREIGN KEY (release_id)
        REFERENCES releases(id),

    CONSTRAINT uq_sbom_documents_release
        UNIQUE (release_id),

    CONSTRAINT chk_sbom_documents_format
        CHECK (bom_format = 'CycloneDX'),

    CONSTRAINT chk_sbom_documents_sha256
        CHECK (document_sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE sbom_components (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sbom_document_id BIGINT NOT NULL,
    bom_ref VARCHAR(255),
    component_type VARCHAR(50) NOT NULL,
    group_name VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    version VARCHAR(255),
    purl TEXT,

    CONSTRAINT fk_sbom_components_document
        FOREIGN KEY (sbom_document_id)
        REFERENCES sbom_documents(id),

    CONSTRAINT uq_sbom_components_document_ref
        UNIQUE (sbom_document_id, bom_ref)
);

CREATE INDEX idx_sbom_components_document
    ON sbom_components (sbom_document_id);