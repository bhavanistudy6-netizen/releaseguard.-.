-- Supports optimistic locking when release status changes.
ALTER TABLE releases
    ADD COLUMN lock_version BIGINT NOT NULL DEFAULT 0;

-- Supports binding decision evidence to the same release.
ALTER TABLE sbom_documents
    ADD CONSTRAINT uq_sbom_documents_id_release
        UNIQUE (id, release_id);

CREATE TABLE release_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    release_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL,
    from_status VARCHAR(30) NOT NULL,
    to_status VARCHAR(30) NOT NULL,

    actor VARCHAR(150) NOT NULL,
    reason TEXT NOT NULL,
    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    sbom_document_id BIGINT,
    vulnerability_import_id BIGINT,
    policy_version VARCHAR(50),

    CONSTRAINT fk_release_decisions_release
        FOREIGN KEY (release_id)
        REFERENCES releases(id),

    CONSTRAINT fk_release_decisions_sbom_release
        FOREIGN KEY (sbom_document_id, release_id)
        REFERENCES sbom_documents(id, release_id),

    CONSTRAINT fk_release_decisions_scan_sbom
        FOREIGN KEY (vulnerability_import_id, sbom_document_id)
        REFERENCES vulnerability_imports(id, sbom_document_id),

    CONSTRAINT chk_release_decisions_actor
        CHECK (length(trim(actor)) > 0),

    CONSTRAINT chk_release_decisions_reason
        CHECK (length(trim(reason)) > 0),

    CONSTRAINT chk_release_decisions_evidence_pair
        CHECK (
            (sbom_document_id IS NULL
                AND vulnerability_import_id IS NULL)
            OR
            (sbom_document_id IS NOT NULL
                AND vulnerability_import_id IS NOT NULL)
        ),

    CONSTRAINT chk_release_decisions_approval_evidence
        CHECK (
            action <> 'APPROVE'
            OR (
                sbom_document_id IS NOT NULL
                AND vulnerability_import_id IS NOT NULL
                AND policy_version IS NOT NULL
                AND length(trim(policy_version)) > 0
            )
        ),

    CONSTRAINT chk_release_decisions_transition
        CHECK (
            (action = 'SUBMIT'
                AND from_status = 'DRAFT'
                AND to_status = 'READY_FOR_REVIEW')
            OR
            (action = 'APPROVE'
                AND from_status = 'READY_FOR_REVIEW'
                AND to_status = 'APPROVED')
            OR
            (action = 'REJECT'
                AND from_status = 'READY_FOR_REVIEW'
                AND to_status = 'DRAFT')
            OR
            (action = 'REVOKE'
                AND from_status = 'APPROVED'
                AND to_status = 'DRAFT')
            OR
            (action = 'RETIRE'
                AND from_status IN (
                    'DRAFT',
                    'READY_FOR_REVIEW',
                    'APPROVED'
                )
                AND to_status = 'RETIRED')
        )
);

CREATE INDEX idx_release_decisions_release_history
    ON release_decisions (release_id, id DESC);

CREATE INDEX idx_release_decisions_scan_sbom
    ON release_decisions (
        vulnerability_import_id,
        sbom_document_id
    );

CREATE INDEX idx_release_decisions_sbom_release
    ON release_decisions (sbom_document_id, release_id);