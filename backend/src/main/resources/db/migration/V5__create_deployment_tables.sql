-- Supports checking that a release belongs to the application.
ALTER TABLE releases
    ADD CONSTRAINT uq_releases_id_application
        UNIQUE (id, application_id);

CREATE TABLE deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    application_id BIGINT NOT NULL,
    release_id BIGINT NOT NULL,
    environment VARCHAR(30) NOT NULL,

    deployed_by VARCHAR(150) NOT NULL,
    deployed_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,

    CONSTRAINT fk_deployments_application
        FOREIGN KEY (application_id)
        REFERENCES applications(id),

    CONSTRAINT fk_deployments_release_application
        FOREIGN KEY (release_id, application_id)
        REFERENCES releases(id, application_id),

    CONSTRAINT uq_deployments_id_application_environment
        UNIQUE (id, application_id, environment),

    CONSTRAINT chk_deployments_environment
        CHECK (
            environment IN (
                'DEVELOPMENT',
                'STAGING',
                'PRODUCTION'
            )
        )
);

CREATE TABLE current_deployments (
    application_id BIGINT NOT NULL,
    environment VARCHAR(30) NOT NULL,
    deployment_id BIGINT NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_current_deployments
        PRIMARY KEY (application_id, environment),

    CONSTRAINT fk_current_deployments_application
        FOREIGN KEY (application_id)
        REFERENCES applications(id),

    CONSTRAINT fk_current_deployments_history
        FOREIGN KEY (
            deployment_id,
            application_id,
            environment
        )
        REFERENCES deployments (
            id,
            application_id,
            environment
        ),

    CONSTRAINT chk_current_deployments_environment
        CHECK (
            environment IN (
                'DEVELOPMENT',
                'STAGING',
                'PRODUCTION'
            )
        )
);

CREATE INDEX idx_deployments_application_environment_history
    ON deployments (application_id, environment, id DESC);

CREATE INDEX idx_deployments_release_application
    ON deployments (release_id, application_id);