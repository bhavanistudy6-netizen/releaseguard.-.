CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(150) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT chk_users_username CHECK (length(trim(username)) >= 3),
    CONSTRAINT chk_users_display_name CHECK (length(trim(display_name)) > 0)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(50) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_user_roles_role CHECK (role IN ('VIEWER', 'DEVELOPER', 'REVIEWER', 'DEPLOYER', 'ADMIN'))
);

CREATE INDEX idx_user_roles_user_id ON user_roles(user_id);

-- Add stable user identifier reference columns to decision and deployment audit tables
ALTER TABLE release_decisions
    ADD COLUMN actor_user_id BIGINT,
    ADD CONSTRAINT fk_release_decisions_user FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE deployments
    ADD COLUMN deployed_by_user_id BIGINT,
    ADD CONSTRAINT fk_deployments_user FOREIGN KEY (deployed_by_user_id) REFERENCES users(id) ON DELETE SET NULL;

